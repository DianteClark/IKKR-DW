"""Generates js/data/itemicons.js: non-empty 16px icon cells of AllItems.png grouped by gear slot."""
import os, json
from PIL import Image
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
im=Image.open(os.path.join(ROOT,'assets/has2020/Items/AllItems.png')).convert('RGBA'); a=im.split()[3]
REG={'armor':[(0,0,320,112),(320,0,640,128)],'boots':[(0,112,320,208)],'shield':[(320,128,640,224)],
'gloves':[(0,208,320,288)],'helm':[(0,288,320,416)],'weapon':[(320,224,640,784)],
'accessory':[(0,496,320,1008),(320,784,640,1008)]}
out={}
for k,rs in REG.items():
    cells=[]
    for x0,y0,x1,y1 in rs:
        for y in range(y0,y1,16):
            for x in range(x0,x1,16):
                bb=a.crop((x,y,x+16,y+16)).getbbox()
                if bb and (bb[2]-bb[0])*(bb[3]-bb[1])>30: cells.append([x//16,y//16])
    out[k]=cells
open(os.path.join(ROOT,'js/data/itemicons.js'),'w').write('// Generated by tools/gen_items.py — [col,row] of 16px cells in AllItems.png per slot\nexport const ITEM_ICONS = '+json.dumps(out)+';\n')
print({k:len(v) for k,v in out.items()})
