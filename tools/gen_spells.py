"""Generates js/data/spells.js from assets/magicbook. Run: python3 -I tools/gen_spells.py"""
import os, json
from PIL import Image
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MB=os.path.join(ROOT,'assets/magicbook')
DMG={'AcidSplash','ChainLightning','DarkExplosion','DeathRipple','DestroyUndead','DisruptingRay','EnergyBlast','Explosion','FallingStars','FireBall','FireWall','FlameStrike','FrostRing','IceBolt','IceSpikes','Iceball','Inferno','Lightning','LightningBolt','MagicArrow','MeteorShower','Shrapnel','Snowball','StoneSpikes','ThunderExplosion','HolyLight','Quicksand','Contusion'}
HEAL={'Cure','Cure 2','Resurrection','AnimateDead'}
DEBUFF={'Blind','Curse','Slow','Weakness','Hypnotize','Charm','AntiMagic','Dispel','Berserk','Transmute','Visions','Disguise','ViewAir','ViewEarth'}
out=[]
for d in sorted(os.listdir(MB)):
    p=os.path.join(MB,d)
    if not os.path.isdir(p): continue
    sheets=[f for f in os.listdir(p) if 'AllFrames' in f and f.endswith('.png')]
    icons=[f for f in os.listdir(p) if f.startswith('Icon') and f.endswith('.png')]
    if not sheets: continue
    im=Image.open(os.path.join(p,sheets[0])); w,h=im.size
    kind='damage' if d in DMG else 'heal' if d in HEAL else 'debuff' if d in DEBUFF else 'buff'
    name=''.join((' '+c if c.isupper() and i>0 and not d[i-1].isupper() else c) for i,c in enumerate(d)).strip()
    out.append({'id':d.replace(' ',''),'name':name,'kind':kind,'src':f'assets/magicbook/{d}/{sheets[0]}','fw':h,'fh':h,'frames':w//h,
                'icon':f'assets/magicbook/{d}/{icons[0]}' if icons else None})
open(os.path.join(ROOT,'js/data/spells.js'),'w').write('// Generated by tools/gen_spells.py\nexport const SPELLS = '+json.dumps(out,indent=1)+';\n')
from collections import Counter
print(len(out), Counter(o['kind'] for o in out), set((o['fw'],o['frames']) for o in out))
