"""Generates js/data/units.js from the creature sprite sheets.
Run: python3 -I tools/gen_units.py  (from repo root)"""
import json, os, sys
from PIL import Image
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BARS={(64,51,83),(32,33,65)}
def scan(path):
    im=Image.open(os.path.join(ROOT,path)).convert('RGBA'); W,H=im.size; px=im.load()
    blocks=[];cur=None;y=0
    while y+16<=H:
        if sum(1 for x in range(W) if px[x,y+3][:3] in BARS)>W*0.3:
            segs=[];x=0
            while x<W:
                if px[x,y+3][:3] in BARS:
                    s=x
                    while x<W and px[x,y+3][:3] in BARS: x+=1
                    segs.append(((s//16)*16,((x+15)//16)*16)) if x-s>=24 else None
                else: x+=1
            cur={'segs':segs,'rows':[]}; blocks.append(cur); y+=16; continue
        if cur is not None:
            p=im.crop((0,y,16,y+16)).split()[3].getbbox()
            if p: cur['rows'].append(y)
        y+=16
    return W,H,blocks
NAMES=['idle','walk','attack','hit','death','special']
def anims(segs):
    return {NAMES[i]:[s[0],(s[1]-s[0])//16] for i,s in enumerate(segs)}
F={}
def faction(fid, path, t1, t2, mode='blocks', pairs=None):
    W,H,b=scan(path)
    a=anims(b[0]['segs'])
    units=[]
    if mode=='blocks':
        base=b[0]['rows'][:len(t1)]; up=b[1]['rows'][:len(t2)] if len(b)>1 and b[1]['rows'] else [None]*len(t1)
        for i,(n1,n2) in enumerate(zip(t1,t2)):
            units.append({'n':[n1,n2],'y':[base[i], up[i] if up[i] is not None else base[i]],'tint2':up[i] is None})
    elif mode=='interleaved':
        rows=b[0]['rows']
        for i,(n1,n2) in enumerate(zip(t1,t2)):
            units.append({'n':[n1,n2],'y':[rows[2*i],rows[2*i+1]],'tint2':False})
    elif mode=='pairs':
        rows=b[0]['rows']
        for (i1,i2),n1,n2 in zip(pairs,t1,t2):
            units.append({'n':[n1,n2],'y':[rows[i1],rows[i2]],'tint2':False})
    F[fid]={'src':path,'anims':a,'units':units}
